package com.learning.constructors2;

public class Laptop {
	String brand;
	String ram;
	String storage;
	double price;
	
	public Laptop(String brand, String ram, String storage, double price) {
		super();
		this.brand = brand;
		this.ram = ram;
		this.storage = storage;
		this.price = price;
	}
	
}
