package Day05ConditionalStatement;

public class Day04SwitchStatement
{
	public static void main(String[] args)
	{	
		int i = 2;
		switch(i){
			case 1:
				System.out.println("i is 1");
				break;
			case 2:
				System.out.println("i is 2");
				break;
			case 3:
				System.out.println("i is 1");
				break;
		}
	}
}